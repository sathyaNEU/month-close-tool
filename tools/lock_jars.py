"""Pin the Spark jar classpath the engine resolves locally (Delta + S3A) for the container images.

The engine's local session resolves ``delta-spark`` and ``hadoop-aws`` through Ivy
(``spark.jars.packages``). This tool builds that same session once, reads the jars Ivy resolved from
``spark.jars``, and records each one with its Maven coordinate and SHA-256 in ``tools/jars.lock``,
leaving out every artifact pyspark already ships, in any version: Spark loads its own jars first
(parent-first class loading), so an older or newer copy on ``--jars`` would never be used anyway, and
it would only carry dead code and its vulnerabilities into the image. Images download exactly these files
from Maven Central with ``tools/fetch_jars.py``, verify every hash, and hand them to spark-submit
with ``--jars`` only, so a container never resolves anything when it starts.

    uv run python tools/lock_jars.py           # rewrite tools/jars.lock
    uv run python tools/lock_jars.py --check   # exit 1 if the resolution no longer matches the lock
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
import tomllib
from pathlib import Path
from urllib.parse import unquote, urlparse

REPO = Path(__file__).resolve().parents[1]
LOCK = REPO / "tools" / "jars.lock"
MAVEN = "https://repo1.maven.org/maven2"
_IVY_NAME = re.compile(r"^(?P<group>[^_]+)_(?P<artifact>.+?)-(?P<version>\d[^-]*(?:-\d+)?(?:\.[A-Za-z]+)?)\.jar$")


def coordinate(ivy_file: str) -> tuple[str, str, str]:
    """``org.apache.hadoop_hadoop-aws-3.4.2.jar`` -> (group, artifact, version)."""
    m = _IVY_NAME.match(ivy_file)
    if m is None:
        raise ValueError(f"not an Ivy jar name: {ivy_file}")
    return m.group("group"), m.group("artifact"), m.group("version")


def maven_url(group: str, artifact: str, version: str) -> str:
    return f"{MAVEN}/{group.replace('.', '/')}/{artifact}/{version}/{artifact}-{version}.jar"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def resolve() -> list[Path]:
    """Jar files Ivy resolves for the engine's local Delta + S3A session."""
    from close_engine.session import LocalSparkOptions, S3Settings, build_local_session

    dummy = S3Settings(endpoint="http://127.0.0.1:1", access_key="lock", secret_key="lock")  # noqa: S106
    spark = build_local_session(LocalSparkOptions(app_name="lock-jars", master="local[1]", s3=dummy))
    try:
        raw = spark.sparkContext.getConf().get("spark.jars") or ""
    finally:
        spark.stop()
    return sorted({Path(unquote(urlparse(u).path)) for u in raw.split(",") if u}, key=lambda p: p.name)


_ARTIFACT = re.compile(r"^(?P<artifact>.+?)-\d")


def bundled_artifacts() -> set[str]:
    """Artifact names (without versions) of the jars inside the pyspark distribution."""
    import pyspark

    names = set()
    for jar in Path(pyspark.__file__).parent.joinpath("jars").glob("*.jar"):
        m = _ARTIFACT.match(jar.name)
        if m:
            names.add(m.group("artifact"))
    return names


def entries() -> list[dict[str, str]]:
    bundled = bundled_artifacts()
    out = []
    for path in resolve():
        group, artifact, version = coordinate(path.name)
        if artifact in bundled:
            continue  # pyspark ships this artifact; its own copy is the one Spark loads
        out.append(
            {
                "coordinate": f"{group}:{artifact}:{version}",
                "file": path.name,
                "url": maven_url(group, artifact, version),
                "sha256": sha256(path),
                "bytes": str(path.stat().st_size),
            }
        )
    return out


def render(items: list[dict[str, str]]) -> str:
    lines = [
        "# Spark classpath for the engine images: delta-spark + hadoop-aws as resolved by Ivy for pyspark,",
        "# minus every artifact pyspark ships itself. Generated by tools/lock_jars.py; do not edit.",
        "# tools/fetch_jars.py downloads each file and fails on any hash mismatch.",
        "",
    ]
    for item in items:
        lines.append("[[jar]]")
        lines.extend(f'{key} = "{value}"' for key, value in item.items() if key != "bytes")
        lines.append(f"bytes = {item['bytes']}")
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="compare against tools/jars.lock instead of writing")
    args = parser.parse_args(argv)
    items = entries()
    if args.check:
        locked = tomllib.loads(LOCK.read_text(encoding="utf-8")).get("jar", [])
        current = {(i["coordinate"], i["sha256"]) for i in items}
        pinned = {(i["coordinate"], i["sha256"]) for i in locked}
        if current != pinned:
            print(f"jars.lock is stale: +{sorted(current - pinned)} -{sorted(pinned - current)}")
            return 1
        print(f"jars.lock matches the resolution ({len(items)} jars)")
        return 0
    LOCK.write_text(render(items), encoding="utf-8")
    total = sum(int(i["bytes"]) for i in items)
    print(f"wrote {LOCK.relative_to(REPO)}: {len(items)} jars, {total / 1e6:.1f} MB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
