"""Generate local-only credentials under .local/secrets/ (gitignored). Idempotent.

All random values live in one file, ``master.json``. Every other file is rendered from it, and a
file that already exists is never rewritten, so running bootstrap twice changes nothing. When a later stage
adds a credential, its value is added to ``master.json`` and its variables are appended to the env files that
lack them; existing values never change. Values that
already existed before ``master.json`` was introduced (the Stage 0 ``s3.env`` and ``compose.env``)
are imported, not regenerated. Nothing here is used outside a developer machine: shared environments
get their secrets from AWS Secrets Manager and Databricks secret scopes.

Each compose service gets only the credentials it needs (least privilege, Stage 1 design rule 6):

  s3.env             host-side tests (SeaweedFS on 127.0.0.1), both identities, Stage 0 parity suite
  seaweedfs-s3.json  identities for the SeaweedFS S3 gateway (writer: read/write, reader: read/list)
  compose.env        compose.test.yaml Postgres (Stage 0 test profile)
  postgres.env       postgres service: superuser plus the role passwords used by the init script
  pg-migrator.env    migrate service: libpq PG* variables for the close_migrator role
  pg-app.env         app service: libpq PG* variables for the close_app role
  pg-ledger-reader.env  jobs service only (Stage 7b): the close_ledger_reader role, which can read only the
                     journals waiting to be posted
  pg-roles.env       pg-roles deploy step only (Stage 7b): the superuser, to create that role, and its password
  s3-writer.env      jobs service only: the writer identity
  s3-reader.env      spark-connect service only (Stage 1b): the read-only identity
  jobs-server.env    jobs emulator: accepted PAT and OAuth client credentials
  jobs-client.env    app: Databricks SDK settings pointing at the emulator (M2M OAuth, like an App)
  app.env            app: the key that signs read-path page cursors (Stage 1b)
"""

from __future__ import annotations

import json
import secrets
from collections.abc import Callable
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SECRETS = REPO / ".local" / "secrets"
MASTER = SECRETS / "master.json"

JOBS_URL = "http://jobs:8080"
S3_INTERNAL = "http://seaweedfs:8333"
S3_HOST = "http://127.0.0.1:8333"


def _write_once(path: Path, content: str) -> bool:
    if path.exists():
        return False
    path.write_text(content, encoding="utf-8")
    path.chmod(0o600)
    return True


def _write_or_extend(path: Path, content: str) -> bool:
    """Write an env file, or append the variables an existing one lacks (existing values never change)."""
    if not path.name.endswith(".env") or not path.exists():
        return _write_once(path, content)
    have = _read_env(path)
    missing = [line for line in content.splitlines() if "=" in line and not line.startswith("#")]
    missing = [line for line in missing if line.split("=", 1)[0] not in have]
    if not missing:
        return False
    with path.open("a", encoding="utf-8") as f:
        f.write("\n".join(missing) + "\n")
    return True


def _read_env(path: Path) -> dict[str, str]:
    if not path.exists():
        return {}
    out = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            out[k] = v
    return out


def _env(title: str, pairs: dict[str, str]) -> str:
    lines = [f"# {title}. Generated by tools/gen_local_secrets.py (local development only)."]
    lines += [f"{k}={v}" for k, v in pairs.items()]
    return "\n".join(lines) + "\n"


def _load_master() -> tuple[dict[str, str], bool]:
    if MASTER.exists():
        master: dict[str, str] = json.loads(MASTER.read_text(encoding="utf-8"))
        added = {k: v for k, v in _ADDED_LATER().items() if k not in master}
        if added:
            master |= added
            MASTER.write_text(json.dumps(master, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        return master, False
    legacy_s3 = _read_env(SECRETS / "s3.env")
    legacy_pg = _read_env(SECRETS / "compose.env")
    token: Callable[[int], str] = secrets.token_urlsafe
    master = {
        "s3_writer_key": legacy_s3.get("CLOSE_S3_ACCESS_KEY", f"closeadmin{secrets.token_hex(4)}"),
        "s3_writer_secret": legacy_s3.get("CLOSE_S3_SECRET_KEY", token(32)),
        "s3_reader_key": legacy_s3.get("CLOSE_S3_READONLY_ACCESS_KEY", f"closereader{secrets.token_hex(4)}"),
        "s3_reader_secret": legacy_s3.get("CLOSE_S3_READONLY_SECRET_KEY", token(32)),
        "pg_test_password": legacy_pg.get("POSTGRES_PASSWORD", token(24)),
        "pg_super_password": token(24),
        "pg_migrator_password": token(24),
        "pg_app_password": token(24),
        "jobs_pat": f"dapi-local-{secrets.token_hex(16)}",
        "jobs_client_id": "close-app-sp-local",
        "jobs_client_secret": token(32),
        "app_hmac_secret": token(32),
        **_ADDED_LATER(),
    }
    return master, True


def _ADDED_LATER() -> dict[str, str]:  # noqa: N802 (a fixed table of later credentials)
    """Credentials added after master.json existed; missing ones are generated once and kept."""
    return {"pg_ledger_reader_password": secrets.token_urlsafe(24)}


def main() -> int:
    SECRETS.mkdir(parents=True, exist_ok=True)
    SECRETS.chmod(0o700)
    m, new_master = _load_master()
    created = []
    if new_master and _write_once(MASTER, json.dumps(m, indent=2, sort_keys=True) + "\n"):
        created.append(MASTER.name)

    pg_common = {"PGHOST": "postgres", "PGPORT": "5432", "PGDATABASE": "close", "PGSSLMODE": "disable"}
    files: dict[str, str] = {
        "s3.env": _env(
            "Host-side tests against SeaweedFS",
            {
                "CLOSE_S3_ENDPOINT": S3_HOST,
                "CLOSE_S3_REGION": "us-east-1",
                "CLOSE_S3_ACCESS_KEY": m["s3_writer_key"],
                "CLOSE_S3_SECRET_KEY": m["s3_writer_secret"],
                "CLOSE_S3_READONLY_ACCESS_KEY": m["s3_reader_key"],
                "CLOSE_S3_READONLY_SECRET_KEY": m["s3_reader_secret"],
                "CLOSE_S3_TEST_BUCKET": "close-lake-test",
            },
        ),
        "seaweedfs-s3.json": json.dumps(
            {
                "identities": [
                    {
                        "name": "close-admin",
                        "credentials": [{"accessKey": m["s3_writer_key"], "secretKey": m["s3_writer_secret"]}],
                        "actions": ["Admin", "Read", "List", "Tagging", "Write"],
                    },
                    {
                        "name": "close-reader",
                        "credentials": [{"accessKey": m["s3_reader_key"], "secretKey": m["s3_reader_secret"]}],
                        "actions": ["Read", "List"],
                    },
                ]
            },
            indent=2,
        )
        + "\n",
        "compose.env": _env(
            "compose.test.yaml Postgres",
            {"POSTGRES_USER": "close", "POSTGRES_PASSWORD": m["pg_test_password"], "POSTGRES_DB": "close"},
        ),
        "postgres.env": _env(
            "postgres service (superuser and role passwords for the init script)",
            {
                "POSTGRES_USER": "postgres",
                "POSTGRES_PASSWORD": m["pg_super_password"],
                "POSTGRES_DB": "close",
                "CLOSE_MIGRATOR_PASSWORD": m["pg_migrator_password"],
                "CLOSE_APP_PASSWORD": m["pg_app_password"],
                "CLOSE_LEDGER_READER_PASSWORD": m["pg_ledger_reader_password"],
            },
        ),
        "pg-migrator.env": _env(
            "migrate service (close_migrator role)",
            {
                **pg_common,
                "PGUSER": "close_migrator",
                "PGPASSWORD": m["pg_migrator_password"],
                "PGAPPNAME": "close-migrate",
            },
        ),
        "pg-app.env": _env(
            "app service (close_app role)",
            {**pg_common, "PGUSER": "close_app", "PGPASSWORD": m["pg_app_password"], "PGAPPNAME": "close-app"},
        ),
        "pg-roles.env": _env(
            "pg-roles deploy step: creates or updates close_ledger_reader as the superuser, and nothing else",
            {
                "PGHOST": "postgres",
                "POSTGRES_USER": "postgres",
                "POSTGRES_PASSWORD": m["pg_super_password"],
                "POSTGRES_DB": "close",
                "CLOSE_LEDGER_READER_PASSWORD": m["pg_ledger_reader_password"],
            },
        ),
        "pg-ledger-reader.env": _env(
            "jobs service: the posting job reads approved journals (close_ledger_reader, one view only)",
            {
                **pg_common,
                "PGUSER": "close_ledger_reader",
                "PGPASSWORD": m["pg_ledger_reader_password"],
                "PGAPPNAME": "close-post-journals",
            },
        ),
        "s3-writer.env": _env(
            "jobs service: writer identity",
            {
                "CLOSE_S3_ENDPOINT": S3_INTERNAL,
                "CLOSE_S3_REGION": "us-east-1",
                "CLOSE_S3_ACCESS_KEY": m["s3_writer_key"],
                "CLOSE_S3_SECRET_KEY": m["s3_writer_secret"],
            },
        ),
        "s3-reader.env": _env(
            "spark-connect service: read-only identity",
            {
                "CLOSE_S3_ENDPOINT": S3_INTERNAL,
                "CLOSE_S3_REGION": "us-east-1",
                "CLOSE_S3_ACCESS_KEY": m["s3_reader_key"],
                "CLOSE_S3_SECRET_KEY": m["s3_reader_secret"],
            },
        ),
        "jobs-server.env": _env(
            "jobs emulator: accepted credentials",
            {
                "EMULATOR_PAT": m["jobs_pat"],
                "EMULATOR_CLIENT_ID": m["jobs_client_id"],
                "EMULATOR_CLIENT_SECRET": m["jobs_client_secret"],
            },
        ),
        "jobs-client.env": _env(
            "app: Databricks SDK settings for the local Jobs API (M2M OAuth, as in a Databricks App)",
            {
                "DATABRICKS_HOST": JOBS_URL,
                "DATABRICKS_CLIENT_ID": m["jobs_client_id"],
                "DATABRICKS_CLIENT_SECRET": m["jobs_client_secret"],
            },
        ),
        "app.env": _env(
            "app: the key that signs read-path page cursors (a Databricks secret in production)",
            {"CLOSE_CURSOR_SECRET": m["app_hmac_secret"]},
        ),
    }
    created += [name for name, content in files.items() if _write_or_extend(SECRETS / name, content)]
    print(f"local secrets: {', '.join(created) if created else 'already present, nothing changed'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
