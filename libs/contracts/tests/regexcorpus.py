"""The regex corpus shared by the unit tests and the Spark portability test."""

from close_contracts.dsl.regex import MAX_LENGTH

ACCEPTED = [
    r"TX(\d{8})XT",  # Adyen-style reference
    r"pmt-([A-Za-z0-9]+)",  # Hyperwallet clientPaymentId
    r"(?i)^ref[:\s]*([0-9]{6,12})",
    r"TRN\*1\*([A-Z0-9]+)",  # BAI2 88-record trace
    r"po_[A-Za-z0-9]{14,40}",  # Stripe payout id
    r"(?:ORD|ORDER)-(\d+)",
    r"[^,]+,([^,]*)",
    r"\bINV\d{4,}\b",
    r"a.b",
    r"[\-a-z]",
    r"[\]\[]",
    r"\x41é",
    r"(\d{2})/(\d{2})/(\d{4})",
    r"[A-Z]{2}\d{2}[A-Z0-9]{1,30}",  # IBAN shape
    r"x{3}",
    r"x{3,}",
    r"x*?y+?z??",
    r"\{literal\}",
    r"(a)(b)(c)",
    r"^\s*$".replace("$", "x"),
]

REJECTED = [
    (r"(a+)+", "nested_quantifier"),
    (r"(a*)*", "nested_quantifier"),
    (r"(a|a)*", "nested_quantifier"),
    (r"(a|aa)+", "nested_quantifier"),
    (r"(\w+\s?)*", "nested_quantifier"),
    (r"((ab)*c)+", "nested_quantifier"),
    (r"(?:x+y)+", "nested_quantifier"),
    (r"(.*a){10}", "nested_quantifier"),
    (r"a*b*c*d*e*", "too_many_unbounded"),
    (r"(?=x)y", "unsupported_group"),
    (r"(?!x)y", "unsupported_group"),
    (r"(?<=x)y", "unsupported_group"),
    (r"(?<!x)y", "unsupported_group"),
    (r"(?<name>x)", "unsupported_group"),
    (r"(?P<name>x)", "unsupported_group"),
    (r"(?>x)", "unsupported_group"),
    (r"a(?i)b", "unsupported_group"),
    (r"(x)\1", "unsupported_escape"),
    (r"\p{Alpha}", "unsupported_escape"),
    (r"\Qx\E", "unsupported_escape"),
    (r"\Ax", "unsupported_escape"),
    (r"x\z", "unsupported_escape"),
    (r"x\Z", "unsupported_escape"),
    (r"\v", "unsupported_escape"),
    (r"x$", "end_anchor"),
    (r"a^b", "anchor_position"),
    (r"a++", "possessive"),
    (r"a*+", "possessive"),
    (r"a**", "nothing_to_repeat"),
    (r"*a", "nothing_to_repeat"),
    (r"^*", "nothing_to_repeat"),
    (r"\b+", "nothing_to_repeat"),
    (r"x{1,2000}", "repeat_too_large"),
    (r"x{5,2}", "bad_repeat"),
    (r"x{", "bad_repeat"),
    (r"[[:alpha:]]", "nested_class"),
    (r"[a-z&&[^e]]", "class_intersection"),
    (r"[]a]", "empty_class"),
    (r"[a-]", "unescaped"),
    (r"[z-a]", "bad_range"),
    (r"[\d-z]", "bad_range"),
    (r"a]", "unescaped"),
    (r"a}", "unescaped"),
    (r"(a", "unbalanced"),
    (r"a)", "unbalanced"),
    (r"[a", "unbalanced"),
    ("a\\", "trailing_backslash"),
    (r"\xZZ", "bad_escape"),
    ("", "empty"),
    ("(?i)", "empty"),
    ("x" * (MAX_LENGTH + 1), "too_long"),
]


